export function getGlossaryForTheme(themeId: number) {
  return glossary.filter((g) => g.themeIds.includes(themeId));
}

export function searchGlossary(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return glossary;
  return glossary.filter((g) =>
    g.term.toLowerCase().includes(q) ||
    g.aka.toLowerCase().includes(q) ||
    g.definition.toLowerCase().includes(q) ||
    g.related.some((r) => r.toLowerCase().includes(q))
  );
}
